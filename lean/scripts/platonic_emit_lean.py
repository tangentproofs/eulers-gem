import pickle, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import platonic_gen, __main__
from platonic_gen import Q
__main__.Q = Q
D = pickle.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'platonic_data.pkl'), 'rb'))

def z(x):
    assert x.a.denominator == 1 and x.b.denominator == 1
    return f"⟨{int(x.a)}, {int(x.b)}⟩"
def v(p): return "⟨" + ", ".join(z(c) for c in p) + "⟩"
def lst(xs): return "[" + ", ".join(str(x) for x in xs) + "]"

INFO = {
 'tetrahedron': ('Tetrahedron', 'tetra', 3, 3, 'four alternate corners of the cube `(±1, ±1, ±1)` with an even number of minus signs'),
 'cube': ('Cube', 'cube', 4, 3, 'the eight points `(±1, ±1, ±1)`'),
 'octahedron': ('Octahedron', 'octa', 3, 4, 'the six points `±eᵢ`'),
 'icosahedron': ('Icosahedron', 'icosa', 3, 5, 'the twelve points `(0, ±1, ±φ)` and their cyclic permutations'),
 'dodecahedron': ('Dodecahedron', 'dodeca', 5, 3, 'the cube corners `(±1, ±1, ±1)` and `(0, ±φ⁻¹, ±φ)` with cyclic permutations, `φ⁻¹ = φ - 1`'),
}

def emit(name):
    d = D[name]; Mod, p, s, m, desc = INFO[name]
    V, F, E = d['V'], d['F'], d['E']
    Eidx = {e: k for k, e in enumerate(E)}; Fidx = {f: k for k, f in enumerate(F)}
    i0, e0, f0 = d['base']
    certs = sorted(d['certs'].items())
    table = []
    for (i, e, f), w in sorted(d['words'].items(), key=lambda kv: (Eidx[kv[0][1]], Fidx[kv[0][2]], kv[0][0])):
        table.append(f"(({i}, {Eidx[e]}, {Fidx[f]}), {lst(w)})")
    out = []
    out.append(f"""/-
Copyright (c) 2026 Michal Wallace / tangentproofs. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Michal Wallace, Grok Bot
-/
import EulersGem.ExplicitRegular

/-!
# The regular {name}

Vertices: {desc} (`φ = Real.goldenRatio`). The face lattice, counts, face type and
flag-transitivity are all decided by the kernel (`decide +kernel`, no `native_decide`) from
the certificate data below, generated by `lean/scripts/platonic_gen.py` and
`lean/scripts/platonic_emit_lean.py`.

* `{p}Data.pts` — the {len(V)} vertices in `ℤ[φ]³`;
* `{p}Data.facets` / `.edges` — the {len(F)} facets and {len(E)} edges as vertex-index lists;
* `{p}Data.certs` — for each of the {len(certs)} non-adjacent vertex pairs, nonnegative weights
  showing the midpoint is a convex combination of the other vertices;
* `{p}Sym` — three mirror normals, the vertex permutations they induce, and a word for each of
  the {len(table)} flags.
-/

namespace EulersGem

namespace Platonic3

open Explicit ZPhi

/-- Certificate data for the {name}. -/
def {p}Data : Data where
  pts := [{(','+chr(10)+'    ').join(v(x) for x in V)}]
  facets := [{', '.join(lst(f) for f in F)}]
  edges := [{', '.join(lst(e) for e in E)}]
  certs := [{(','+chr(10)+'    ').join(f"(({i}, {j}), ({den}, [{', '.join(f'({u}, {z(c)})' for u, c in nu)}]))" for (i, j), (nu, den) in certs)}]

/-- Mirror generators and flag words for the {name}. -/
def {p}Sym : Data.Sym where
  gens := [{', '.join(v(g) for g in d['gens'])}]
  perms := [{', '.join(lst(pi) for pi in d['perms'])}]
  base := ({i0}, {Eidx[e0]}, {Fidx[f0]})
  table := [{(','+chr(10)+'    ').join(table)}]

theorem {p}_checkAll : {p}Data.checkAll = true := by decide +kernel

theorem {p}_checkType : {p}Data.checkType {s} {m} = true := by decide +kernel

theorem {p}_checkFlags : {p}Sym.checkFlags {p}Data = true := by decide +kernel

end Platonic3

end EulersGem
""")
    return Mod, "".join(out)

if __name__ == '__main__':
    import os
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    for name in INFO:
        Mod, txt = emit(name)
        open(os.path.join(outdir, Mod + '.lean'), 'w').write(txt)
        print('wrote', Mod)
